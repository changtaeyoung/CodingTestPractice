SELECT A.AUTHOR_ID, A.AUTHOR_NAME, B.CATEGORY, SUM(C.BSCNT * B.PRICE) AS TOTAL_SALES
FROM BOOK B
    INNER JOIN (SELECT BOOK_ID, SUM(SALES) AS BSCNT
        FROM BOOK_SALES
        WHERE YEAR(SALES_DATE) = '2022' AND MONTH(SALES_DATE) = '01'
        GROUP BY BOOK_ID) C
    ON B.BOOK_ID = C.BOOK_ID
    INNER JOIN AUTHOR A
    ON B.AUTHOR_ID = A.AUTHOR_ID
GROUP BY A.AUTHOR_ID, B.CATEGORY
ORDER BY 1, 3 DESC

